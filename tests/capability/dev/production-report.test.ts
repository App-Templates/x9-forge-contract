import { describe, expect, it } from 'vitest';
import { canonicalizeDevProductionReport as canonicalize, DevProductionJobSchema, type DevProductionJob } from '../../../src/capability/dev/production-job.js';

const scope = { tenantId: 'tenant-1', ownerId: 'owner-1', agentId: 'agent-1' };
const job: DevProductionJob = {
  version: 1, scope, jobId: 'job-1', requestId: 'request_12345678', projectId: 'project-1',
  session: { scope, sessionId: 'session-1', target: { kind: 'local', deviceId: 'device-1' }, engines: ['codex', 'claude'] },
  productKind: 'code', instruction: '  Crea caffè ☕\n第二行\t "ok"  ', reportVersion: 1,
  reportDigest: 'a'.repeat(64), configVersion: 0, keyVersion: 1,
  limits: { maxDurationSeconds: 600, maxAttempts: 2, maxTasks: 3 },
};
// Independent literal, including JSON escapes; never generated by the implementation.
const expected = '{"domain":"x9.cap-dev.production-report","job":{"configVersion":0,"instruction":"  Crea caffè ☕\\n第二行\\t \\"ok\\"  ","jobId":"job-1","keyVersion":1,"limits":{"maxAttempts":2,"maxDurationSeconds":600,"maxTasks":3},"productKind":"code","projectId":"project-1","reportVersion":1,"requestId":"request_12345678","scope":{"agentId":"agent-1","ownerId":"owner-1","tenantId":"tenant-1"},"session":{"engines":["claude","codex"],"scope":{"agentId":"agent-1","ownerId":"owner-1","tenantId":"tenant-1"},"sessionId":"session-1","target":{"deviceId":"device-1","kind":"local"}},"version":1},"version":1}';

describe('canonicalizeDevProductionReport', () => {
  it('matches literal compact UTF-8 JSON with Unicode and newlines', () => {
    expect(canonicalize(job) === expected).toBe(true);
    expect(Buffer.from(canonicalize(job), 'utf8')).toEqual(Buffer.from(expected, 'utf8'));
  });
  it('includes instruction', () => {
    expect(canonicalize(job).includes('"instruction":')).toBe(true);
  });
  it('includes limits', () => {
    expect(canonicalize(job).includes('"limits":')).toBe(true);
  });
  it('includes target', () => {
    expect(canonicalize(job).includes('"target":')).toBe(true);
  });
  it('sorts nested object keys', () => {
    expect(canonicalize(job).includes('"scope":{"agentId":"agent-1","ownerId":"owner-1","tenantId":"tenant-1"}')).toBe(true);
  });
  it('sorts engines as a set', () => {
    expect(canonicalize(job).includes('"engines":["claude","codex"]')).toBe(true);
  });
  it('excludes reportDigest only', () => {
    expect(canonicalize(job) === canonicalize({ ...job, reportDigest: 'b'.repeat(64) })).toBe(true);
  });
  it('preserves every instruction character', () => {
    expect(canonicalize(job) !== canonicalize({ ...job, instruction: job.instruction + ' ' })).toBe(true);
  });
  it('ignores input key order recursively without mutating input', () => {
    function reverseKeys(value: unknown): unknown {
      if (Array.isArray(value)) return value.map(reverseKeys);
      if (value !== null && typeof value === 'object') {
        return Object.fromEntries(Object.entries(value).reverse().map(([key, child]) => [key, reverseKeys(child)]));
      }
      return value;
    }
    const input = { ...job, session: { ...job.session, engines: [...job.session.engines].reverse() } };
    const before = JSON.stringify(input);
    expect(canonicalize(reverseKeys(input))).toBe(expected);
    expect(JSON.stringify(input)).toBe(before);
    expect(job.session.engines).toEqual(['codex', 'claude']);
  });

  const changes: [string, (copy: DevProductionJob) => void][] = [
    ['jobId', copy => { copy.jobId += '-2'; }],
    ['requestId', copy => { copy.requestId += '2'; }],
    ['projectId', copy => { copy.projectId += '-2'; }],
    ['instruction', copy => { copy.instruction += ' '; }],
    ['productKind', copy => { copy.productKind = 'automation'; }],
    ['reportVersion', copy => { copy.reportVersion++; }],
    ['configVersion', copy => { copy.configVersion++; }],
    ['keyVersion', copy => { copy.keyVersion++; }],
    ['maxDurationSeconds', copy => { copy.limits.maxDurationSeconds++; }],
    ['maxAttempts', copy => { copy.limits.maxAttempts++; }],
    ['maxTasks', copy => { copy.limits.maxTasks++; }],
    ['sessionId', copy => { copy.session.sessionId += '-2'; }],
    ['deviceId', copy => { copy.session.target = { kind: 'local', deviceId: 'device-2' }; }],
    ['target kind', copy => { copy.session.target = { kind: 'cloud', connectionRef: 'cloud-1' }; }],
    ['engines', copy => { copy.session.engines = ['codex']; }],
    ...(['tenantId', 'ownerId', 'agentId'] as const).map(key => [key, (copy: DevProductionJob) => {
      copy.scope[key] += '-2'; copy.session.scope[key] += '-2';
    }] satisfies [string, (copy: DevProductionJob) => void]),
  ];
  it.each(changes)('binds %s with otherwise valid input', (_name, change) => {
    const copy = structuredClone(job);
    change(copy);
    expect(DevProductionJobSchema.safeParse(copy).success).toBe(true);
    expect(canonicalize(copy)).not.toBe(canonicalize(job));
  });
  it('binds the cloud connection reference', () => {
    const cloud = { ...job, session: { ...job.session, target: { kind: 'cloud', connectionRef: 'cloud-1' } } };
    expect(canonicalize(cloud)).not.toBe(canonicalize({ ...cloud, session: { ...cloud.session, target: { kind: 'cloud', connectionRef: 'cloud-2' } } }));
  });
  it.each([
    null, { ...job, version: 2 }, { ...job, instruction: '' }, { ...job, reportDigest: 'bad' },
    { ...job, extra: true }, { ...job, limits: { ...job.limits, maxTasks: 0 } },
    { ...job, session: { ...job.session, engines: ['codex', 'codex'] } },
    { ...job, session: { ...job.session, scope: { ...scope, ownerId: 'other' } } },
  ])('rejects invalid job %#', input => {
    expect(() => canonicalize(input)).toThrow();
  });
});
