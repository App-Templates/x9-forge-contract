import { createHash } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import { SignedApprovalPermitSchema } from '../../../src/capability/approvals/index.js';
import {
  canonicalizeDevProductionReport as canonicalize, devProductionApprovalBindings, DevProductionJobSchema, type DevProductionJob,
} from '../../../src/capability/dev/production-job.js';
import { isDevProductionApprovalForJob as matches } from '../../../src/http/endpoints/internal-dev-production.js';

const scope = { tenantId: 'tenant-1', ownerId: 'owner-1', agentId: 'agent-1' };
const job: DevProductionJob = {
  version: 1, scope, jobId: 'job-1', requestId: 'request_12345678', projectId: 'project-1',
  session: { scope, sessionId: 'session-1', target: { kind: 'local', deviceId: 'device-1' }, engines: ['codex', 'claude'] },
  productKind: 'code', instruction: '  Crea caffè ☕\n第二行\t "ok"  ', reportVersion: 1,
  reportDigest: 'a'.repeat(64), configVersion: 0, keyVersion: 1,
  limits: { maxDurationSeconds: 600, maxAttempts: 2, maxTasks: 3 },
};
const roleModels = {
  coordination: { engine: 'claude', modelId: 'model-coord', reasoningEffort: 'medium' },
  planning: { engine: 'claude', modelId: 'model-plan', reasoningEffort: 'high' },
  unblocking: { engine: 'codex', modelId: 'model-unblock', reasoningEffort: 'medium' },
  code: { engine: 'codex', modelId: 'model-code', reasoningEffort: 'high' },
  design: { engine: 'claude', modelId: 'model-design' },
  presentation: { engine: 'codex', modelId: 'model-deck', reasoningEffort: 'low' },
};
type Roles = typeof roleModels;
const withRoles = (roles: unknown = roleModels, extra: Record<string, unknown> = {}) => ({ ...job, ...extra, roleModels: roles });
const sha = (text: string) => createHash('sha256').update(text, 'utf8').digest('hex');

// Independent literals, never generated by the implementation.
const historical = '{"domain":"x9.cap-dev.production-report","job":{"configVersion":0,"instruction":"  Crea caffè ☕\\n第二行\\t \\"ok\\"  ","jobId":"job-1","keyVersion":1,"limits":{"maxAttempts":2,"maxDurationSeconds":600,"maxTasks":3},"productKind":"code","projectId":"project-1","reportVersion":1,"requestId":"request_12345678","scope":{"agentId":"agent-1","ownerId":"owner-1","tenantId":"tenant-1"},"session":{"engines":["claude","codex"],"scope":{"agentId":"agent-1","ownerId":"owner-1","tenantId":"tenant-1"},"sessionId":"session-1","target":{"deviceId":"device-1","kind":"local"}},"version":1},"version":1}';
const rolesLiteral = '"roleModels":{"code":{"engine":"codex","modelId":"model-code","reasoningEffort":"high"},"coordination":{"engine":"claude","modelId":"model-coord","reasoningEffort":"medium"},"design":{"engine":"claude","modelId":"model-design"},"planning":{"engine":"claude","modelId":"model-plan","reasoningEffort":"high"},"presentation":{"engine":"codex","modelId":"model-deck","reasoningEffort":"low"},"unblocking":{"engine":"codex","modelId":"model-unblock","reasoningEffort":"medium"}}';
const expectedWithRoles = historical.replace('"requestId":"request_12345678",', `"requestId":"request_12345678",${rolesLiteral},`);

function reverseKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(reverseKeys);
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).reverse().map(([key, child]) => [key, reverseKeys(child)]));
  }
  return value;
}
const roleNames = Object.keys(roleModels) as (keyof Roles)[];

describe('bridge221 production role models in the approved report', () => {
  it('keeps the historical report byte for byte without roleModels', () => {
    expect(DevProductionJobSchema.safeParse(job).success).toBe(true);
    expect(canonicalize(job) === historical).toBe(true);
    expect(canonicalize(job).includes('roleModels')).toBe(false);
  });

  it('round-trips the six role choices through the job', () => {
    const parsed = DevProductionJobSchema.safeParse(withRoles());
    expect(parsed.success).toBe(true);
    expect(parsed.success ? parsed.data.roleModels : undefined).toEqual(roleModels);
    expect(JSON.parse(JSON.stringify(parsed.success ? parsed.data : null))).toEqual(withRoles());
  });

  it('is not changed by the order of the keys', () => {
    const input = withRoles();
    const before = JSON.stringify(input);
    expect(canonicalize(reverseKeys(input)) === expectedWithRoles).toBe(true);
    expect(canonicalize(input) === expectedWithRoles).toBe(true);
    expect(JSON.stringify(input)).toBe(before);
  });

  it('binds engine, model and reasoning of a role in the text', () => {
    const base = canonicalize(withRoles());
    const changes: Record<string, unknown>[] = [
      { ...roleModels.code, engine: 'claude' },
      { ...roleModels.code, modelId: 'model-code-2' },
      { ...roleModels.code, reasoningEffort: 'low' },
      { engine: 'codex', modelId: 'model-code' },
    ];
    for (const choice of changes) {
      const changed = withRoles({ ...roleModels, code: choice });
      expect(DevProductionJobSchema.safeParse(changed).success).toBe(true);
      expect(canonicalize(changed) === base).toBe(false);
    }
  });

  it('binds each of the six roles in the SHA-256 of the text', () => {
    const baseSha = sha(canonicalize(withRoles()));
    for (const role of roleNames) {
      const changed = withRoles({ ...roleModels, [role]: { ...roleModels[role], modelId: `${roleModels[role].modelId}-2` } });
      expect(DevProductionJobSchema.safeParse(changed).success).toBe(true);
      expect(sha(canonicalize(changed)) === baseSha).toBe(false);
    }
  });

  it('keeps the supplied reportDigest out of the text with roleModels', () => {
    expect(canonicalize(withRoles(roleModels, { reportDigest: 'c'.repeat(64) })) === canonicalize(withRoles())).toBe(true);
  });

  it('rejects the old permit after a model change and admits the one for the new expectation', () => {
    const now = Date.parse('2026-10-16T01:01:00Z');
    const permitFor = (current: DevProductionJob, textSha256: string) => SignedApprovalPermitSchema.parse({
      permit: { v: 1, client: 'dev', type: 'dev.produce', ...scope, requestId: current.requestId,
        textSha256, bindings: devProductionApprovalBindings(current),
        issuedAt: '2026-10-16T01:00:00Z', expiresAt: '2026-10-16T01:05:00Z', nonce: 'n'.repeat(22) },
      keyId: 'key-1', signature: 's'.repeat(86),
    });
    const approved = (roles: unknown) => {
      const text = canonicalize(withRoles(roles));
      return DevProductionJobSchema.parse({ ...withRoles(roles), reportDigest: sha(text) });
    };
    const oldJob = approved(roleModels);
    const newJob = approved({ ...roleModels, planning: { ...roleModels.planning, reasoningEffort: 'low' } });
    const oldPermit = permitFor(oldJob, oldJob.reportDigest);
    const newPermit = permitFor(newJob, newJob.reportDigest);
    expect(newJob.reportDigest === oldJob.reportDigest).toBe(false);
    // Pure correlation only: it never replaces the signature, nonce and state checks of S3.
    expect(matches(oldPermit, oldJob, oldJob.reportDigest, now)).toBe(true);
    expect(matches(oldPermit, newJob, newJob.reportDigest, now)).toBe(false);
    expect(matches(newPermit, newJob, newJob.reportDigest, now)).toBe(true);
    expect(matches(newPermit, oldJob, oldJob.reportDigest, now)).toBe(false);
  });

  it('rejects a role engine outside the session engines', () => {
    const session = { ...job.session, engines: ['codex'] };
    const outside = { ...withRoles(), session };
    expect(DevProductionJobSchema.safeParse(outside).success).toBe(false);
    expect(() => canonicalize(outside)).toThrow();
    const inside = withRoles(Object.fromEntries(roleNames.map(role => [role, { ...roleModels[role], engine: 'codex' }])));
    expect(DevProductionJobSchema.safeParse({ ...inside, session }).success).toBe(true);
  });

  it('rejects incomplete, unknown or malformed role choices', () => {
    const incomplete = Object.fromEntries(Object.entries(roleModels).filter(([role]) => role !== 'design'));
    const bad = [
      incomplete, { ...roleModels, extra: roleModels.code }, { ...roleModels, code: { ...roleModels.code, extra: 1 } },
      { ...roleModels, code: { engine: 'codex' } }, { ...roleModels, code: { ...roleModels.code, engine: 'other' } },
      { ...roleModels, code: { ...roleModels.code, modelId: ' ' } }, [], null,
    ];
    for (const roles of bad) expect(DevProductionJobSchema.safeParse(withRoles(roles)).success).toBe(false);
  });
});
