import { z } from 'zod';
import { AssetKeySchema } from '../../organization/asset.js';
import { PAPERCLIP_CRITERI_MASSIMI, PAPERCLIP_CRITERIO_MAX } from '../paperclip-protocollo/wire-creazione.js';

// Only variable criteria consume Paperclip slots; versioned template checks live in the catalog.
export const DEV_SESSION_ACCEPTANCE_MAX_CRITERIA = PAPERCLIP_CRITERI_MASSIMI;
export const DEV_SESSION_CRITERION_TEXT_MAX = PAPERCLIP_CRITERIO_MAX;
export const DEV_SESSION_ATTESTORS = ['sessione', 'esecutore', 'revisore', 'referente'] as const;
export const DEV_SESSION_CRITERION_ORIGINS = ['mandato', 'capo', 'ritorno'] as const;
export const DEV_SESSION_INPUT_DATA = ['veri', 'di_prova', 'da_inventare'] as const;
export const DEV_SESSION_INPUT_STATES = ['pieno', 'vuoto', 'errore', 'caricamento'] as const;
export const DEV_SESSION_INPUT_FORMATS = ['telefono', 'computer'] as const;
export const DEV_SESSION_INPUT_VISUAL_SOURCES = ['figma', 'tavola_approvata', 'nessuna'] as const;
// consumers key their per-code moves on this list (R-14)
export const DEV_SESSION_ACCEPTANCE_SCHEMA_ISSUES = ['reference_iff_return', 'executor_only_from_catalog', 'mandate_not_session', 'unit_only_mandate', 'proof_script_name', 'screens_not_unique', 'behaviors_not_unique', 'list_not_unique', 'visual_reference_rule', 'criterion_ids_not_unique'] as const;
type AcceptanceSchemaIssue = (typeof DEV_SESSION_ACCEPTANCE_SCHEMA_ISSUES)[number];
// Identity helper: a message outside the list above does not compile.
const ruleIssue = (code: AcceptanceSchemaIssue): AcceptanceSchemaIssue => code;

export const DevSessionAttestorSchema = z.enum(DEV_SESSION_ATTESTORS);
export type DevSessionAttestor = z.infer<typeof DevSessionAttestorSchema>;
export const DevSessionCriterionOriginSchema = z.enum(DEV_SESSION_CRITERION_ORIGINS);
export type DevSessionCriterionOrigin = z.infer<typeof DevSessionCriterionOriginSchema>;

const CriterionIdSchema = z.string().min(1).max(40).regex(/^[A-Za-z0-9]+([-_.][A-Za-z0-9]+)*$/);
const CriterionTextSchema = z.string().trim().min(1).max(DEV_SESSION_CRITERION_TEXT_MAX);

export const DevSessionCriterionSchema = z.strictObject({
  id: CriterionIdSchema,
  text: CriterionTextSchema,
  attestor: DevSessionAttestorSchema,
  proof: CriterionTextSchema,
  origin: DevSessionCriterionOriginSchema,
  reference: z.string().trim().min(1).max(200).optional(),
  unit: AssetKeySchema.max(30).optional(),
}).superRefine((criterion, ctx) => {
  if ((criterion.origin === 'ritorno') !== (criterion.reference !== undefined)) ctx.addIssue({ code: 'custom', path: ['reference'], message: ruleIssue('reference_iff_return') });
  // Executor attestations are generated by the catalog, never accepted from free-form criteria.
  if (criterion.attestor === 'esecutore') ctx.addIssue({ code: 'custom', path: ['attestor'], message: ruleIssue('executor_only_from_catalog') });
  if (criterion.origin === 'mandato' && criterion.attestor === 'sessione') ctx.addIssue({ code: 'custom', path: ['attestor'], message: ruleIssue('mandate_not_session') });
  if (criterion.unit !== undefined && criterion.origin !== 'mandato') ctx.addIssue({ code: 'custom', path: ['unit'], message: ruleIssue('unit_only_mandate') });
});
export type DevSessionCriterion = z.infer<typeof DevSessionCriterionSchema>;

// Presence is owned by the chosen template; the wire contract only validates supplied inputs.
export const DevSessionAcceptanceInputSchema = z.strictObject({
  userPath: z.array(CriterionTextSchema).min(1).max(20).optional(),
  data: z.enum(DEV_SESSION_INPUT_DATA).optional(),
  // A script name is resolved by the consumer, so shell commands cannot cross this boundary.
  proofScripts: z.array(z.string().regex(/^[a-z0-9][a-z0-9:_.-]{0,59}$/, ruleIssue('proof_script_name'))).min(1).max(10).optional(),
  screens: z.array(z.strictObject({ name: AssetKeySchema, purpose: z.string().trim().min(1).max(200) })).min(1).max(20)
    .refine((screens) => new Set(screens.map((screen) => screen.name)).size === screens.length, ruleIssue('screens_not_unique')).optional(),
  behaviors: z.array(AssetKeySchema).min(1).max(20)
    .refine((behaviors) => new Set(behaviors).size === behaviors.length, ruleIssue('behaviors_not_unique')).optional(),
  states: z.array(z.enum(DEV_SESSION_INPUT_STATES))
    .refine((states) => new Set(states).size === states.length, ruleIssue('list_not_unique')).optional(),
  formats: z.array(z.enum(DEV_SESSION_INPUT_FORMATS))
    .refine((formats) => new Set(formats).size === formats.length, ruleIssue('list_not_unique')).optional(),
  visualSource: z.strictObject({
    kind: z.enum(DEV_SESSION_INPUT_VISUAL_SOURCES),
    reference: z.string().trim().min(1).max(512).optional(),
  }).superRefine((source, ctx) => {
    if ((source.kind !== 'nessuna') !== (source.reference !== undefined)) ctx.addIssue({ code: 'custom', path: ['reference'], message: ruleIssue('visual_reference_rule') });
  }).optional(),
  retouch: z.strictObject({ target: CriterionTextSchema, defect: CriterionTextSchema }).optional(),
});
export type DevSessionAcceptanceInput = z.infer<typeof DevSessionAcceptanceInputSchema>;

export const DevSessionAcceptanceSchema = z.strictObject({
  version: z.literal(1),
  template: z.strictObject({
    id: AssetKeySchema.min(2),
    version: z.number().int().min(1),
    optionalIds: z.array(CriterionIdSchema).min(1).max(10)
      .refine((ids) => new Set(ids).size === ids.length, ruleIssue('list_not_unique')).optional(),
  }),
  input: DevSessionAcceptanceInputSchema,
  criteria: z.array(DevSessionCriterionSchema).min(1).max(DEV_SESSION_ACCEPTANCE_MAX_CRITERIA)
    .refine((criteria) => new Set(criteria.map((criterion) => criterion.id)).size === criteria.length, ruleIssue('criterion_ids_not_unique')),
});
export type DevSessionAcceptance = z.infer<typeof DevSessionAcceptanceSchema>;
